import assert from 'node:assert/strict';
import {renderItemInfo,renderOrderItems} from '../orders/item-info.js';
const raw={id:1,name:'小麦',buildingName:'农田',level:1,stepMinutes:2,analysisBatchYield:1,inputs:[],coinValue:0};
const other={...raw,id:2,name:'糖<测试>',stepMinutes:10,coinValue:null};
const flour={...raw,id:3,name:'面粉',buildingName:'石磨',stepMinutes:5,inputs:[{id:1,quantity:3}]};
const cake={...raw,id:4,name:'糕点',buildingName:'糕坊',level:8,stepMinutes:20,inputs:[{id:3,quantity:2},{id:2,quantity:1}],coinValue:null};
const products=new Map([raw,other,flour,cake].map(p=>[p.id,p]));
let html=renderItemInfo(cake,products,7);
assert(html.includes('面粉<b>×2</b>')&&html.includes('糖&lt;测试&gt;<b>×1</b>'));
assert(!html.includes('×14')&&!html.includes('糖<测试>'),'recipe is per batch and all names are escaped');
assert(html.includes('累计复杂度</dt><dd>4 种')&&html.includes('单品累计工时</dt><dd>52 分钟'));
assert(html.includes('本单需求 7 个')&&html.includes('单价</dt><dd title="">未导入'));
html=renderItemInfo(raw,products,7);assert(html.includes('无需原料')&&html.includes('0 金币')&&html.includes('2 分钟'));
html=renderItemInfo({...cake,unitCumulativeMinutes:125,cumulativeComplexity:3},products,1);assert(html.includes('125 分钟')&&html.includes('3 种'),'existing imported metrics take precedence');
html=renderItemInfo({...cake,analysisBatchYield:2},products,1);assert(html.includes('每批产出 2 个')&&html.includes('面粉<b>×2</b>'));
html=renderItemInfo({...cake,inputs:[{id:99,quantity:2}]},products,1);assert(html.includes('未知商品 99')&&html.includes('未提供')&&!html.includes('NaN'));
const before=JSON.stringify([...products]);renderItemInfo(cake,products,3);assert.equal(JSON.stringify([...products]),before);
assert(!renderItemInfo(cake,products).includes('本单需求'),'product statistics have no invented order quantity');
assert(renderOrderItems({items:[{id:4,quantity:7}]},products).includes('data-product-id="4" data-quantity="7"'));
console.log('Item tooltips: direct recipe, quantities, escaping, unit work, complexity, missing/zero prices and non-mutation passed.');
